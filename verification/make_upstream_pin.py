"""Generate verification/generated/UpstreamPin.lean from the vendored upstream file.

The upstream file (google-deepmind/formal-conjectures, FormalConjectures/ErdosProblems/1186.lean, vendored verbatim in
verification/upstream/) cannot be imported here: it is a `module` file that depends on the FormalConjecturesUtil
package. Instead this script copies, VERBATIM (byte for byte, docstrings included), from that file

  * the three definitions `monoCount`, `minMonoCount` and `δ`, and
  * the statements of the four theorems `erdos_1186.variants.prs_bounds`, `prs_conjecture`, `van_der_waerden`,
    `probabilistic` (docstring and the text from `theorem` to `:=`; only the `@[category ...]` attribute line, which
    needs FormalConjecturesUtil, and the upstream proof `by sorry` are left out)

into a separate namespace `Upstream1186`. It then states that our definitions are definitionally equal to the copied
ones (`rfl`), and proves each copied statement, about the COPIED `δ`, from the corresponding theorem of this repository.
Lean checks all of it; nothing is retyped by hand. A copied statement that differed from ours would fail to compile.

Usage (from the repository root):  py verification/make_upstream_pin.py
The generated file is then checked from lean/:  lake env lean ../verification/generated/UpstreamPin.lean
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
UPSTREAM = ROOT / "upstream" / "FormalConjectures_ErdosProblems_1186.lean"
OUT = ROOT / "generated" / "UpstreamPin.lean"
NS = "Upstream1186"

# (upstream theorem name, the binders it takes, the theorem of this repository that proves it)
THEOREMS = [
    ("erdos_1186.variants.prs_bounds", "", "Erdos1186Day.erdos_1186.variants.prs_bounds"),
    ("erdos_1186.variants.prs_conjecture", "", "Erdos1186Day.erdos_1186.variants.prs_conjecture"),
    ("erdos_1186.variants.van_der_waerden", "k hk", "Erdos1186Day.erdos_1186.variants.van_der_waerden"),
    ("erdos_1186.variants.probabilistic", "k hk", "Erdos1186Day.erdos_1186.variants.probabilistic"),
]


def docstring_before(lines, i):
    """Index of the first line of the docstring that ends on line i - 1 (or i if there is none)."""
    if i > 0 and lines[i - 1].rstrip().endswith("-/"):
        j = i - 1
        while not lines[j].lstrip().startswith("/--"):
            j -= 1
        return j
    return i


def def_block(lines, start_marker):
    """The declaration starting with `start_marker`, with its docstring, up to the next blank line."""
    i = next(k for k, s in enumerate(lines) if s.startswith(start_marker))
    j = docstring_before(lines, i)
    k = i
    while k < len(lines) and lines[k].strip():
        k += 1
    return lines[j:k]


def theorem_block(lines, name):
    """(docstring lines, statement lines) of `theorem name`: the statement runs from `theorem` to the `:=`
    that ends it; the `@[category ...]` line between docstring and theorem is dropped."""
    i = next(k for k, s in enumerate(lines) if re.match(r"theorem " + re.escape(name) + r"(\s|$)", s))
    a = i
    if a > 0 and lines[a - 1].startswith("@["):
        a -= 1
    j = docstring_before(lines, a)
    doc = lines[j:a]
    stmt = []
    k = i
    while True:
        stmt.append(lines[k])
        if ":=" in lines[k]:
            break
        k += 1
    last = stmt[-1]
    head, tail = last.split(":=", 1)
    if tail.strip() not in ("by", "by sorry") or (tail.strip() == "by" and lines[k + 1].strip() != "sorry"):
        raise SystemExit(f"unexpected upstream proof of {name}: {tail.strip()!r}")
    stmt[-1] = head.rstrip()
    return doc, stmt


def main():
    raw = UPSTREAM.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    commit = (ROOT / "upstream" / "COMMIT.txt").read_text(encoding="utf-8").split()[0]
    lines = raw.decode("utf-8").splitlines()
    assert "namespace Erdos1186" in lines and "open Filter Asymptotics" in lines
    defs = [def_block(lines, m) for m in ("def monoCount ", "noncomputable def minMonoCount ", "noncomputable def δ ")]
    out = [
        "import Erdos1186",
        "",
        "/-! GENERATED by verification/make_upstream_pin.py. Do not edit.",
        f"Namespace `{NS}` holds the definitions `monoCount`, `minMonoCount`, `δ` and the statements of four theorems,",
        "copied verbatim (docstrings included) from FormalConjectures/ErdosProblems/1186.lean; the `@[category ...]`",
        "attribute lines and the upstream proofs (`by sorry`) are left out. The theorems after the namespace state that",
        "our definitions are definitionally equal to the copied ones, and the copied statements, which refer to the",
        "copied `δ`, are proved from the theorems of this repository. -/",
        "",
        f"-- source: upstream/{UPSTREAM.name}, formal-conjectures commit {commit}, file sha256 {sha}",
        "",
        "open Filter Asymptotics",
        "",
        f"namespace {NS}",
        "",
    ]
    for d in defs:
        out += d + [""]
    out += [f"end {NS}", ""]
    out += [
        f"/-- Our `monoCount` is definitionally the upstream one. -/",
        f"theorem pin_monoCount : Erdos1186Day.monoCount = {NS}.monoCount := rfl",
        "",
        f"/-- Our `minMonoCount` is definitionally the upstream one. -/",
        f"theorem pin_minMonoCount : Erdos1186Day.minMonoCount = {NS}.minMonoCount := rfl",
        "",
        f"/-- Our `δ` is definitionally the upstream one. -/",
        f"theorem pin_delta : Erdos1186Day.δ = {NS}.δ := rfl",
        "",
        f"namespace {NS}",
        "",
    ]
    for name, args, ours in THEOREMS:
        doc, stmt = theorem_block(lines, name)
        call = f"{ours} {args}".rstrip()
        out += doc + stmt[:-1] + [stmt[-1] + " := by", "  rw [← pin_delta]", f"  exact {call}", ""]
        print(f"{name}: copied {len(doc)} docstring lines + {len(stmt)} statement lines; proved by {ours}")
    out += [f"end {NS}", ""]
    out += ["#print axioms pin_monoCount", "#print axioms pin_minMonoCount", "#print axioms pin_delta"]
    out += [f"#print axioms {NS}.{name}" for name, _, _ in THEOREMS]
    out += [""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes("\n".join(out).encode("utf-8"))
    print(f"{UPSTREAM.name}: sha256 {sha}, commit {commit}; definitions copied: "
          + ", ".join(f"{len(d)} lines" for d in defs) + f"; wrote {OUT.relative_to(ROOT.parent).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
