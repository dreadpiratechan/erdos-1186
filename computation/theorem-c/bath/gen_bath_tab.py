"""Erdos 1186 exbath: certificate tables (nu_i, T_i) per cell for the Lean bathtub check.

nu_i = min over the unit cells p of cell i of min(alpha_p, alpha_p + beta_p);
T_i  = max over integer levels c >= 0 of  sum_p [e_p <= c < e_p + s_p] * (6 / s_p),  e_p = min(alpha_p, alpha_p+beta_p) - nu_i, s_p = |beta_p|.
Writes lean/Erdos/Proofs/P1186ExBathTab.lean (only a certificate: the Lean check re-verifies every inequality it needs).
"""
import io, json, sys
from fractions import Fraction as Fr
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gen_interface import c1
ROOT = Path(__file__).resolve().parents[3]  # the repository root
G = json.load(io.open(ROOT / "computation/theorem-c/data/grids.json", encoding="utf-8"))
def Uk(k): return 1 if c1(k // 2 + 1) else -1
FU = [0]
for k in range(1200): FU.append(FU[-1] + Uk(k))
def ab(p1):  # p1 = p' (0-indexed unit cell)
    p = p1 + 1
    k1 = (p + 1095) // 2; k2 = (p - 1) // 2; e = (p - 1) % 2
    D = (Uk(k1) - Uk(k2)) // 2
    Up = Uk(p - 1)
    if p <= 548:
        T = FU[2 * p - 2]; Tu = Uk(2 * p - 2)
        return -Up * (FU[k1] - FU[k2] + e * D + T), -Up * (D + 2 * Tu)
    T = FU[2 * p - 1098]; Tu = Uk(2 * p - 1098)
    return -Up * (FU[k1] - FU[k2] + e * D - T), -Up * (D - 2 * Tu)
AB = [ab(p) for p in range(1096)]
out = {}
tot_terms = 0
for name in ("g24", "g8"):
    pts = G[name]["pts"]; N = len(pts) - 1
    nus, Ts = [], []
    for i in range(N):
        lo, hi = pts[i], pts[i + 1]; L = hi - lo
        d = [min(AB[p][0], AB[p][0] + AB[p][1]) for p in range(lo, hi)]
        s = [abs(AB[p][1]) for p in range(lo, hi)]
        nu = min(d)
        e = [x - nu for x in d]
        assert all(1 <= x <= 3 and 6 % x == 0 for x in s)
        assert all(ee + ss <= 3 * L for ee, ss in zip(e, s)), (name, i)
        T = max(sum(6 // ss for ee, ss in zip(e, s) if ee <= c < ee + ss) for c in range(3 * L))
        assert Fr(G[name]["a"][i]) * 1096 * 2192 == L * nu, (name, i)
        assert Fr(G[name]["b"][i]) * 4 * 1096 ** 2 * T == 6 * L * L, (name, i)
        tot_terms += 3 * L * L
        nus.append(nu); Ts.append(T)
    out[name] = (nus, Ts)
print("terms (3 L^2 summed)", tot_terms)
L = ["import Mathlib", "", "/-!", "# Erdos 1186 - certificate tables for the bathtub check (generated, do not edit)", "",
     "Formalises the proof claimed on erdosproblems.com/1186 (Proof claims, 2026-10-05, unrefereed); the mathematics is its",
     "author's.  Generated by `problems/1186/exact/bath/gen_bath_tab.py`.  Per cell `i`: `nu i` is the least value of the unit-cell",
     "profile `H2 / w` and `T i` six times the largest slope sum of the level-count function.  These are only a certificate:",
     "`P1186ExBathCell.cellChk` re-checks every inequality it uses.", "-/", "", "namespace Erdos1186Ex", ""]
for name, ln in (("g24", "24"), ("g8", "8")):
    nus, Ts = out[name]
    L.append(f"def nuTab{ln} : List ℤ := [" + ", ".join(map(str, nus)) + "]")
    L.append(f"def tTab{ln} : List ℕ := [" + ", ".join(map(str, Ts)) + "]")
    L.append("")
L += ["end Erdos1186Ex", ""]
io.open(ROOT / "lean/Erdos/Proofs/P1186ExBathTab.lean", "w", encoding="utf-8", newline="\n").write("\n".join(L))
print("wrote P1186ExBathTab.lean")
