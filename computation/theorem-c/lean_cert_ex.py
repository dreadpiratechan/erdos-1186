def main():
    global TRI_CHUNK, TRI_GROUP
    ap = argparse.ArgumentParser()
    ap.add_argument("--regions", type=int, nargs="*", default=[4])
    ap.add_argument("--prows", type=int, default=30)
    ap.add_argument("--drows", type=int, default=200, help="thousand multiply-adds per dominance chunk")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check-only", action="store_true")
    ap.add_argument("--tchunk", type=int, default=TRI_CHUNK, help="triangles per sub-chunk")
    ap.add_argument("--tgroup", type=int, default=TRI_GROUP, help="sub-chunks per group (one kernel declaration per group)")
    a = ap.parse_args()
    TRI_CHUNK, TRI_GROUP = a.tchunk, a.tgroup
    outdir = Path(a.out)
    for r in a.regions:
        o = cm.build(r)
        t = make_tabs(o)
        bad = semantic_check(t)
        print("region", r, "n", t.n, "mirror failures:", bad, "| widths Wg %d Wa %d Wf %d Wt %d Wn %d" % (t.Wg, t.Wa, t.Wf, t.Wt, t.Wn))
        if bad:
            sys.exit(1)
