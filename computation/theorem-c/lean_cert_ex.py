# ----------------------------------------------------------------------------------------------- packing
def width(vals):
    m = max(abs(int(v)) for v in vals) if vals else 0
    return m.bit_length() + 2


def pack(vals, W):
    off = 1 << (W - 1)
    acc = 0
    for j, v in enumerate(vals):
        d = int(v) + off
        assert 0 <= d < (1 << W), (v, W)
        acc |= d << (W * j)
    return acc


def unpack(r, W, j):
    return ((r >> (W * j)) & ((1 << W) - 1)) - (1 << (W - 1))


def hexlit(x):
    return "0x%x" % x


def lst(items):
    return "[" + ", ".join(items) + "]"


# ----------------------------------------------------------------------------------------------- tables
class Tabs:
    pass


def make_tabs(o):
    n = o.n
    t = Tabs()
    t.o = o
    t.n = n
    t.Wg = width(o.lo + o.hi + o.len + [1, -1])
    t.vlo, t.vhi, t.vlen, t.vsg = (pack(v, t.Wg) for v in (o.lo, o.hi, o.len, o.sgn))
    t.Wa = width(o.alpha + o.beta)
    t.vAl, t.vBt = pack(o.alpha, t.Wa), pack(o.beta, t.Wa)
    fvals = o.Yv + o.Ov + o.A1 + o.A2 + o.A3 + o.A4w + [x for r in (o.YY, o.OO, o.YO) for row in r for x in row]
    t.Wf = width(fvals)
    t.vYv, t.vOv, t.vA1, t.vA2, t.vA3, t.vA4 = (pack(v, t.Wf) for v in (o.Yv, o.Ov, o.A1, o.A2, o.A3, o.A4w))
    t.YYT = [pack(row, t.Wf) for row in o.YY]
    t.OOT = [pack(row, t.Wf) for row in o.OO]
    t.YOT = [pack(row, t.Wf) for row in o.YO]
    t.Wt = width([x for row in o.theta for x in row])
    t.thT = [pack(row, t.Wt) for row in o.theta]
    N = cm.padded_N(o)
    t.Wn = width([x for row in N for x in row])
    t.NT = [pack(row, t.Wn) for row in N]
    rows = [[int(x) for x in r] for r in o.d["chol"]["rows"]]
    assert int(o.d["chol"]["T2"]) == 1
    if o.d["const_row_zero"]:
        rows = [[0]] + [[0] + r for r in rows]
    assert len(rows) == n + 1
    t.crows = rows
    t.N = N
    t.czr = [sum(cm.pair_coefs(o, i, j)[2] for j in range(n)) for i in range(n)]
    t.tris, t.triS = tri_state(o, n)
    if t.tris:
        tri_pack(t)
    return t


def tri_state(o, n):
    """The list of triangles (w = Zn * num) and the dense accumulated coefficients (c, l, q)."""
    tris = []
    c = 0
    l = [0] * n
    q = [[0] * n for _ in range(n)]
    for tr in o.tri:
        i, j, k, s1, s2, s3, num = [int(x) for x in tr]
        assert 0 <= i < n and 0 <= j < n and 0 <= k < n and num >= 0
        assert all(x in (1, -1) for x in (s1, s2, s3)) and s1 * s2 * s3 == 1
        w = o.Zn * num
        tris.append((i, j, k, s1, s2, s3, w))
        c += w * (1 + s1 + s2 + s3)
        l[i] += w * (-2 * (s1 + s3))
        l[j] += w * (-2 * (s1 + s2))
        l[k] += w * (-2 * (s2 + s3))
        q[i][j] += w * (4 * s1)
        q[j][k] += w * (4 * s2)
        q[i][k] += w * (4 * s3)
    return tris, (c, l, q)


def group_sums(tris, n, W):
    """The integers the kernel computes for a group of triangles: sum of cterm, lterm, qterm and wterm."""
    cs = ws = 0
    ls = qs = 0
    for (i, j, k, s1, s2, s3, w) in tris:
        cs += w * (1 + s1 + s2 + s3)
        ws += w
        ls += (w * (-2 * (s1 + s3))) * (1 << (W * i)) + (w * (-2 * (s1 + s2))) * (1 << (W * j)) \
            + (w * (-2 * (s2 + s3))) * (1 << (W * k))
        qs += (w * (4 * s1)) * (1 << (W * (n * i + j))) + (w * (4 * s2)) * (1 << (W * (n * j + k))) \
            + (w * (4 * s3)) * (1 << (W * (n * i + k)))
    return cs, ls, qs, ws


def tri_pack(t):
    """Design C: the final tables are packed (base 2^W, digits offset by 2^(W-1)); the groups of triangles carry the
    exact integer sums that the kernel recomputes."""
    n = t.n
    c, l, q = t.triS
    sw = sum(x[6] for x in t.tris)
    t.triW = (12 * sw).bit_length() + 2
    W = t.triW
    assert 12 * sw < (1 << (W - 1))
    t.triCc = c
    t.triL = pack(l, W)
    t.triQR = [pack(row, W) for row in q]
    t.tchunks = split(len(t.tris), TRI_CHUNK)          # sub-chunks (a, m)
    t.tgroups = split(len(t.tchunks), TRI_GROUP)       # groups of sub-chunks (a, m)
    t.gsums = []
    for (ga, gm) in t.tgroups:
        lo_i = t.tchunks[ga][0]
        last = t.tchunks[ga + gm - 1]
        hi_i = last[0] + last[1]
        t.gsums.append(group_sums(t.tris[lo_i:hi_i], n, W))


def semantic_check(t):
    """Re-derive in Python every identity the Lean checks evaluate.  Returns the number of failures."""
    o, n = t.o, t.n
    bad = 0
    # round trip of the packing
    for i in range(n):
        for j in range(n):
            assert unpack(t.YYT[i], t.Wf, j) == o.YY[i][j]
            assert unpack(t.OOT[i], t.Wf, j) == o.OO[i][j]
            assert unpack(t.YOT[i], t.Wf, j) == o.YO[i][j]
            assert unpack(t.thT[i], t.Wt, j) == o.theta[i][j]
    for i in range(n + 1):
        for j in range(n + 1):
            assert unpack(t.NT[i], t.Wn, j) == t.N[i][j]
    for i in range(n):
        assert unpack(t.vlo, t.Wg, i) == o.lo[i] and unpack(t.vhi, t.Wg, i) == o.hi[i]
        assert unpack(t.vlen, t.Wg, i) == o.len[i] and unpack(t.vsg, t.Wg, i) == o.sgn[i]
        assert unpack(t.vAl, t.Wa, i) == o.alpha[i] and unpack(t.vBt, t.Wa, i) == o.beta[i]
    # ranges
    for i in range(n):
        for j in range(n):
            assert 0 <= o.theta[i][j] <= cm.Q
            assert o.YY[i][j] >= 0 and o.OO[i][j] >= 0 and o.YO[i][j] >= 0
    for v in (o.Yv, o.Ov, o.A1, o.A2, o.A3, o.A4w):
        assert all(x >= 0 for x in v)
    assert o.p >= 0 and o.r_ >= 0 and o.s >= 0 and o.Zn > 0
    # entry equations
    if o.tri:
        c, l, q = t.triS
        U = cm.U
        c0t, lt, qt, _ = cm.tri_poly(o)
        # the accumulated coefficients and the independent mirror formulas agree
        if U * c != c0t:
            bad += 1
            print("tri constant differs")
        if [U * x for x in l] != lt:
            bad += 1
            print("tri linear differs")
        for a in range(n):
            for b in range(n):
                if U * (q[a][b] + q[b][a]) != qt[a][b] + qt[b][a]:
                    bad += 1
        bad += cm.check_entries(o, (U * c, [U * x for x in l], [[U * x for x in row] for row in q]))
        # the packed tables decode to the coefficients, and the group sums add up to them (as the kernel will check)
        W = t.triW
        H = 1 << (W - 1)
        for a in range(n):
            if unpack(t.triL, W, a) != l[a]:
                bad += 1
            for b in range(n):
                if unpack(t.triQR[a], W, b) != q[a][b]:
                    bad += 1
        offL = sum(H << (W * a) for a in range(n))
        offQ = sum(offL << (W * n * a) for a in range(n))
        tot = [sum(g[x] for g in t.gsums) for x in range(4)]
        if tot[0] != c:
            bad += 1
            print("group constants do not add up")
        if tot[1] + offL != t.triL:
            bad += 1
            print("group linear sums do not add up")
        if tot[2] + offQ != sum(r << (W * n * a) for a, r in enumerate(t.triQR)):
            bad += 1
            print("group quadratic sums do not add up")
        if not (12 * tot[3] < H):
            bad += 1
            print("weight bound fails")
        if not all(r < (1 << (W * n)) for r in t.triQR):
            bad += 1
            print("row range fails")
    else:
        bad += cm.check_entries(o)
    # symmetry and dominance of N - C C^T
    C, N = t.crows, t.N
    for a in range(n + 1):
        s = 0
        Ea = None
        row = []
        for b in range(n + 1):
            assert N[a][b] == N[b][a]
            e = N[a][b] - sum(x * y for x, y in zip(C[a], C[b]))
            row.append(e)
        if sum(abs(e) for e in row) > 2 * row[a]:
            bad += 1
            print("dominance fails in row", a)
    return bad


